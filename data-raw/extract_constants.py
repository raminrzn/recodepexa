"""Extract the RECODe equations from the authors' Shiny app into R/constants.R.

usage: python3 -I data-raw/extract_constants.py app.R appSI.R R/constants.R

Source: github.com/sanjaybasu/t2dmriskeqns, commit 63135bd8 (app.R and
appSI.R). Each outcome in app.R is written as
  round(100*(1 - S0^exp(0 + b1 * as.numeric(input$x1) + ... + offset)))
The script reads S0, each coefficient with its input name, and the offset as
written (no code is run), and checks that appSI.R has the same numbers.
"""
import re, sys

def parse(text):
    out = {}
    for m in re.finditer(r"(\w+)_beta\s*=\s*reactive\(\{round\(100\*\(1-\s*([0-9.]+)\^exp\(0\s*\+(.*?)\)\)\)\s*\}\)", text, re.S):
        name, s0, body = m.group(1), float(m.group(2)), m.group(3)
        terms = re.findall(r"([-+]?\s*[0-9.]+(?:e[-+]?\d+)?)\s*\*\s*as\.numeric\(input\$(\w+)\)", body)
        coefs = {}
        for c, v in terms:
            coefs[v] = float(re.sub(r"\s+", "", c))
        rest = re.sub(r"[-+]?\s*[0-9.]+(?:e[-+]?\d+)?\s*\*\s*as\.numeric\(input\$\w+\)(\s*\*\s*[0-9.]+/[0-9.]+)?", "", body)
        nums = re.findall(r"[-+]?\s*[0-9.]+(?:e[-+]?\d+)?", rest)
        assert len(nums) == 1, (name, rest)
        offset = float(re.sub(r"\s+", "", nums[0]))
        out[name] = dict(s0=s0, coefs=coefs, offset=offset)
    return out

app, appsi = parse(open(sys.argv[1]).read()), parse(open(sys.argv[2]).read())
assert list(app) == ["neph", "retin", "neuro", "mi", "chf", "death"], list(app)
for k in app:
    assert app[k] == appsi[k], ("app.R and appSI.R differ for", k)
names = {"neph": "nephropathy", "retin": "retinopathy", "neuro": "neuropathy",
         "mi": "ascvd", "chf": "chf", "death": "mortality"}
lines = ["# Generated by data-raw/extract_constants.py from the RECODe Shiny app",
         "# (github.com/sanjaybasu/t2dmriskeqns, commit 63135bd8, app.R; appSI.R has",
         "# identical numbers). Risk = 1 - s0^exp(sum(coef * x) + offset). Do not edit.",
         "", ".rc_eq <- list("]
items = []
for k, v in app.items():
    coefs = ", ".join("%s = %r" % (var, c) for var, c in v["coefs"].items())
    items.append("  %s = list(s0 = %r, offset = %r,\n    coef = c(%s))" % (names[k], v["s0"], v["offset"], coefs))
lines.append(",\n".join(items))
lines.append(")")
open(sys.argv[3], "w").write("\n".join(lines) + "\n")
print("wrote", sys.argv[3], {names[k]: len(v["coefs"]) for k, v in app.items()})
